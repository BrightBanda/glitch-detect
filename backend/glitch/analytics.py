"""Anonymous, aggregate usage analytics for the admin dashboard.

The app has no accounts, so analytics must never pretend to know who a person
is. This module stores only per-day counters and random browser IDs. Request
text, API keys, labels, IP addresses and user agents are never written. Browser
IDs are used solely to count unique active browsers over rolling windows.

Analytics are persisted beside the key store (``instance/analytics.json``) so
they survive a restart. The file is intentionally small: one record per day for
the last ~13 months, plus one record per browser seen in that time.
"""

from __future__ import annotations

import json
import logging
import os
import secrets
import threading
import time
from datetime import date, timedelta
from pathlib import Path

from . import config

log = logging.getLogger("glitch")

COOKIE_NAME = "glitch_visitor"
COOKIE_MAX_AGE = 365 * 24 * 60 * 60
RETENTION_DAYS = 400
API_ENDPOINTS = ("analyze", "humanize", "models", "identify")
ENDPOINT_LABELS = {
    "analyze": "Checks",
    "humanize": "Rewrites",
    "models": "Model lists",
    "identify": "Key identification",
}


def new_client_id() -> str:
    """A random, anonymous browser identifier. Never derived from a person."""
    return secrets.token_urlsafe(18)


def valid_client_id(value: object) -> bool:
    """Accept only identifiers generated by :func:`new_client_id`."""
    if not isinstance(value, str) or not 16 <= len(value) <= 64:
        return False
    return all(ch.isalnum() or ch in "-_" for ch in value)


def _as_int(value: object, default: int = 0) -> int:
    try:
        return int(value)  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return default


def _empty_bucket() -> dict:
    return {"requests": 0, "errors": 0, "duration_ms": 0, "words": 0, "tokens": 0}


def _empty_day() -> dict:
    return {
        "visits": 0,
        "requests": 0,
        "errors": 0,
        "words": 0,
        "tokens": 0,
        "duration_ms": 0,
        "endpoints": {},
        "providers": {},
        "clients": {},
    }


def _clean_bucket(raw: object) -> dict:
    bucket = _empty_bucket()
    if not isinstance(raw, dict):
        return bucket
    for name in bucket:
        bucket[name] = max(0, _as_int(raw.get(name)))
    return bucket


def _clean_day(raw: object) -> dict:
    day = _empty_day()
    if not isinstance(raw, dict):
        return day
    for name in ("visits", "requests", "errors", "words", "tokens", "duration_ms"):
        day[name] = max(0, _as_int(raw.get(name)))
    for name in ("endpoints", "providers"):
        entries = raw.get(name)
        if isinstance(entries, dict):
            day[name] = {
                str(key): _clean_bucket(value)
                for key, value in entries.items()
                if isinstance(key, str) and key
            }
    clients = raw.get("clients")
    if isinstance(clients, dict):
        day["clients"] = {
            str(key): 1
            for key, value in clients.items()
            if valid_client_id(key) and value
        }
    elif isinstance(clients, list):
        day["clients"] = {str(key): 1 for key in clients if valid_client_id(key)}
    return day


def _clean_client(raw: object) -> dict | None:
    if not isinstance(raw, dict):
        return None
    first = str(raw.get("first") or "")
    last = str(raw.get("last") or "")
    if not first or not last:
        return None
    return {
        "first": first,
        "last": last,
        "visits": max(0, _as_int(raw.get("visits"))),
        "requests": max(0, _as_int(raw.get("requests"))),
    }


class AnalyticsStore:
    """Thread-safe, file-backed counters for anonymous usage analytics."""

    def __init__(self, path: Path | None = None, retention_days: int = RETENTION_DAYS):
        self._path = path or (config.INSTANCE_DIR / "analytics.json")
        self._retention_days = retention_days
        self._lock = threading.Lock()
        self._data: dict | None = None

    # -- persistence -------------------------------------------------------
    def _load(self) -> dict:
        if self._data is not None:
            return self._data
        days: dict[str, dict] = {}
        clients: dict[str, dict] = {}
        try:
            raw = json.loads(self._path.read_text(encoding="utf-8"))
            if isinstance(raw, dict):
                raw_days = raw.get("days")
                if isinstance(raw_days, dict):
                    days = {
                        str(key): _clean_day(value)
                        for key, value in raw_days.items()
                        if isinstance(key, str) and key
                    }
                raw_clients = raw.get("clients")
                if isinstance(raw_clients, dict):
                    for key, value in raw_clients.items():
                        client = _clean_client(value)
                        if valid_client_id(key) and client:
                            clients[str(key)] = client
        except FileNotFoundError:
            pass
        except (OSError, ValueError):
            log.warning("analytics file could not be read; starting a new one")
        self._data = {"version": 1, "days": days, "clients": clients}
        self._prune(self._data)
        return self._data

    def _prune(self, data: dict) -> None:
        cutoff = (date.today() - timedelta(days=self._retention_days - 1)).isoformat()
        for day in [key for key in data["days"] if key < cutoff]:
            del data["days"][day]
        for client_id in [
            key
            for key, value in data["clients"].items()
            if str(value.get("last") or "") < cutoff
        ]:
            del data["clients"][client_id]

    def _save(self) -> None:
        data = self._data or {"version": 1, "days": {}, "clients": {}}
        self._prune(data)
        self._path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self._path.with_suffix(".tmp")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            json.dump(data, handle, indent=2, sort_keys=True)
        os.replace(tmp, self._path)

    def reset(self) -> None:
        """Discard all analytics. Used by tests and the future reset control."""
        with self._lock:
            self._data = {"version": 1, "days": {}, "clients": {}}
            self._save()

    # -- recording --------------------------------------------------------
    def record(
        self,
        endpoint: str,
        *,
        status_code: int = 200,
        duration_ms: int = 0,
        client_id: str = "",
        provider: str = "",
        words: int = 0,
        tokens: int = 0,
    ) -> None:
        """Record one page visit or API call without storing request content."""
        is_page = endpoint == "page"
        today = date.today().isoformat()
        failed = status_code >= 400
        duration_ms = max(0, _as_int(duration_ms))
        words = max(0, _as_int(words))
        tokens = max(0, _as_int(tokens))

        with self._lock:
            data = self._load()
            day = _clean_day(data["days"].get(today))
            if is_page:
                day["visits"] += 1
            else:
                day["requests"] += 1
                day["duration_ms"] += duration_ms
                endpoint_bucket = _clean_bucket(day["endpoints"].get(endpoint))
                endpoint_bucket["requests"] += 1
                endpoint_bucket["duration_ms"] += duration_ms
                if failed:
                    day["errors"] += 1
                    endpoint_bucket["errors"] += 1
                else:
                    day["words"] += words
                    day["tokens"] += tokens
                    endpoint_bucket["words"] += words
                    endpoint_bucket["tokens"] += tokens
                day["endpoints"][endpoint] = endpoint_bucket

            if provider and not is_page:
                provider_bucket = _clean_bucket(day["providers"].get(provider))
                provider_bucket["requests"] += 1
                if failed:
                    provider_bucket["errors"] += 1
                else:
                    provider_bucket["words"] += words
                    provider_bucket["tokens"] += tokens
                day["providers"][provider] = provider_bucket

            if client_id:
                if not valid_client_id(client_id):
                    client_id = ""
                else:
                    day["clients"][client_id] = 1
                    client = data["clients"].get(client_id) or {
                        "first": today,
                        "last": today,
                        "visits": 0,
                        "requests": 0,
                    }
                    client["last"] = today
                    if is_page:
                        client["visits"] = _as_int(client.get("visits")) + 1
                    else:
                        client["requests"] = _as_int(client.get("requests")) + 1
                    data["clients"][client_id] = client

            data["days"][today] = day
            self._save()

    # -- reporting --------------------------------------------------------
    @staticmethod
    def _active_ids(days: dict, start: date, end: date) -> set[str]:
        active: set[str] = set()
        for key, day in days.items():
            if start.isoformat() <= key <= end.isoformat():
                active.update(day.get("clients", {}).keys())
        return active

    @staticmethod
    def _stats(days: dict, start: date, end: date) -> dict:
        totals = {
            "requests": 0,
            "errors": 0,
            "words": 0,
            "tokens": 0,
            "duration_ms": 0,
            "visits": 0,
        }
        endpoints: dict[str, dict] = {}
        providers: dict[str, dict] = {}
        active: set[str] = set()
        for key, day in days.items():
            if not start.isoformat() <= key <= end.isoformat():
                continue
            for name in totals:
                totals[name] += _as_int(day.get(name))
            active.update(day.get("clients", {}).keys())
            for name, raw in day.get("endpoints", {}).items():
                bucket = endpoints.setdefault(name, _empty_bucket())
                for field in bucket:
                    bucket[field] += _as_int(raw.get(field))
            for name, raw in day.get("providers", {}).items():
                bucket = providers.setdefault(name, _empty_bucket())
                for field in bucket:
                    bucket[field] += _as_int(raw.get(field))

        def avg_ms(bucket: dict) -> int:
            requests = _as_int(bucket.get("requests"))
            return round(_as_int(bucket.get("duration_ms")) / requests) if requests else 0

        checks = _as_int(endpoints.get("analyze", {}).get("requests"))
        rewrites = _as_int(endpoints.get("humanize", {}).get("requests"))
        return {
            **totals,
            "active": len(active),
            "checks": checks,
            "rewrites": rewrites,
            "avg_ms": avg_ms(totals),
            "endpoints": [
                {"id": name, **bucket, "avg_ms": avg_ms(bucket)}
                for name, bucket in endpoints.items()
            ],
            "providers": [
                {"id": name, **bucket, "avg_ms": avg_ms(bucket)}
                for name, bucket in providers.items()
            ],
        }

    def snapshot(self) -> dict:
        """Return dashboard-ready totals. Never includes individual browser IDs."""
        today = date.today()
        windows = {
            "today": today,
            "week": today - timedelta(days=6),
            "month": today - timedelta(days=29),
            "year": today - timedelta(days=364),
        }
        with self._lock:
            data = self._load()
            days = data["days"]
            clients = data["clients"]
            stats = {name: self._stats(days, start, today) for name, start in windows.items()}
            active = {
                name: len(self._active_ids(days, start, today))
                for name, start in windows.items()
            }
            month_start = windows["month"].isoformat()
            new_month = sum(
                1 for client in clients.values() if str(client.get("first") or "") >= month_start
            )
            total_browsers = len(clients)
            first_day = min(days) if days else ""
            last_day = max(days) if days else ""
            series = []
            for offset in range(29, -1, -1):
                day_date = today - timedelta(days=offset)
                day = _clean_day(days.get(day_date.isoformat()))
                endpoint_counts = {
                    name: _as_int(bucket.get("requests"))
                    for name, bucket in day.get("endpoints", {}).items()
                }
                series.append(
                    {
                        "date": day_date.isoformat(),
                        "requests": day["requests"],
                        "checks": endpoint_counts.get("analyze", 0),
                        "rewrites": endpoint_counts.get("humanize", 0),
                        "tokens": day["tokens"],
                        "visits": day["visits"],
                        "active": len(day.get("clients", {})),
                    }
                )
            month = stats["month"]
            return {
                "generated_at": int(time.time()),
                "today": today.isoformat(),
                "windows": stats,
                "active": {
                    "day": active["today"],
                    "week": active["week"],
                    "month": active["month"],
                    "year": active["year"],
                    "new_month": new_month,
                    "total": total_browsers,
                },
                "series": series,
                "coverage": {"first_day": first_day, "last_day": last_day},
                "plans": {
                    "connected": False,
                    "paid": None,
                    "free": None,
                    "note": (
                        "This build has no accounts, subscriptions or payment records, "
                        "so paid and free users cannot be counted yet."
                    ),
                },
                "empty": not month["requests"] and not month["visits"],
            }


store = AnalyticsStore()
